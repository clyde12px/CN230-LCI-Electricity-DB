-- Preflight validation: any failure aborts the transaction before target inserts.
DO $$
DECLARE
    v_stage_count INTEGER;
    v_month_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_stage_count FROM stg_egat_fuel;
    SELECT COUNT(DISTINCT (reference_year, reference_month)) INTO v_month_count
    FROM stg_egat_fuel;

    IF v_stage_count <> 1913 THEN
        RAISE EXCEPTION 'Expected 1913 source rows, found %', v_stage_count;
    END IF;

    IF v_month_count <> 486 THEN
        RAISE EXCEPTION 'Expected 486 distinct year-months, found %', v_month_count;
    END IF;

    IF EXISTS (
        SELECT 1 FROM stg_egat_fuel
        GROUP BY reference_year, reference_month, fuel_type
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Duplicate Year-Month-Fuel rows found in staging data';
    END IF;

    IF EXISTS (SELECT 1 FROM stg_egat_fuel WHERE amount < 0 OR reference_month NOT BETWEEN 1 AND 12) THEN
        RAISE EXCEPTION 'Negative amount or invalid month found';
    END IF;

    IF EXISTS (
        SELECT 1 FROM stg_egat_fuel s
        LEFT JOIN lci_electricity.lci_flow f
          ON f.flow_id = s.flow_id AND f.flow_name = s.flow_name
        LEFT JOIN lci_electricity.unit u
          ON u.unit_id = s.unit_id AND u.unit_symbol = s.unit_name
        WHERE f.flow_id IS NULL OR u.unit_id IS NULL
    ) THEN
        RAISE EXCEPTION 'A required flow or unit ID/name does not match current master data';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM lci_electricity.lci_source WHERE source_id = 1)
       OR NOT EXISTS (SELECT 1 FROM lci_electricity.technology WHERE technology_id = 1)
       OR NOT EXISTS (SELECT 1 FROM lci_electricity.geography WHERE geography_id = 1) THEN
        RAISE EXCEPTION 'Required source_id=1, technology_id=1, or geography_id=1 is missing';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM lci_electricity.lci_process p
        JOIN (SELECT DISTINCT reference_year, reference_month FROM stg_egat_fuel) s
          ON p.process_name = 'EGAT Fuel Consumption - '
             || s.reference_year::TEXT || '-'
             || LPAD(s.reference_month::TEXT, 2, '0')
    ) THEN
        RAISE EXCEPTION 'Matching monthly process already exists; import stopped to prevent duplicates';
    END IF;
END $$;

-- One aggregated process for each year-month with at least one source record.
INSERT INTO lci_electricity.lci_process
(process_name, technology_id, reference_year, geography_id, source_id, domain, description, reference_month)
SELECT
    'EGAT Fuel Consumption - ' || m.reference_year::TEXT || '-' || LPAD(m.reference_month::TEXT, 2, '0'),
    1,
    m.reference_year,
    1,
    1,
    'Electricity Generation',
    'Monthly aggregated EGAT fuel consumption; national-level data, not plant-specific and not normalized per kWh. Source CSV: Fuel Consumption by EGAT.',
    m.reference_month
FROM (
    SELECT DISTINCT reference_year, reference_month
    FROM stg_egat_fuel
) AS m
ORDER BY m.reference_year, m.reference_month;

-- Each source fuel row becomes one INPUT exchange, preserving its original unit and amount.
INSERT INTO lci_electricity.lci_exchange
(process_id, flow_id, direction, amount, unit_id, is_reference_flow, source_id, notes)
SELECT
    p.process_id,
    s.flow_id,
    'INPUT',
    s.amount,
    s.unit_id,
    FALSE,
    1,
    'Source CSV row ' || s.source_csv_row::TEXT
      || '; original fuel type: ' || s.fuel_type
      || '; original unit: ' || s.unit_name
      || '; source: https://www.thaigovdata.com/en/datasets/dataset-11-312'
FROM stg_egat_fuel s
JOIN lci_electricity.lci_process p
  ON p.process_name = 'EGAT Fuel Consumption - '
     || s.reference_year::TEXT || '-'
     || LPAD(s.reference_month::TEXT, 2, '0');

-- Post-insert checks are still inside the transaction.
DO $$
DECLARE
    v_process_count INTEGER;
    v_exchange_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_process_count
    FROM lci_electricity.lci_process
    WHERE process_name LIKE 'EGAT Fuel Consumption - ____-__';

    SELECT COUNT(*) INTO v_exchange_count
    FROM lci_electricity.lci_exchange e
    JOIN lci_electricity.lci_process p ON p.process_id = e.process_id
    WHERE p.process_name LIKE 'EGAT Fuel Consumption - ____-__'
      AND e.source_id = 1
      AND e.direction = 'INPUT';

    IF v_process_count <> 486 THEN
        RAISE EXCEPTION 'Post-check failed: expected 486 monthly processes, found %', v_process_count;
    END IF;

    IF v_exchange_count <> 1913 THEN
        RAISE EXCEPTION 'Post-check failed: expected 1913 exchanges, found %', v_exchange_count;
    END IF;
END $$;

COMMIT;

