        RAISE EXCEPTION 'EPPO row count mismatch: expected 3381, got %', v_count;
    END IF;
    IF v_months <> 486 THEN
        RAISE EXCEPTION 'EPPO month count mismatch: expected 486, got %', v_months;
    END IF;
    IF v_fuels <> 7 THEN
        RAISE EXCEPTION 'EPPO fuel count mismatch: expected 7, got %', v_fuels;
    END IF;
    IF EXISTS (
        SELECT 1 FROM eppo_values
        WHERE reference_year NOT BETWEEN 1900 AND 2200
           OR reference_month NOT BETWEEN 1 AND 12
           OR amount < 0
           OR unit_text <> 'GWh'
           OR flow_id NOT BETWEEN 6 AND 12
    ) THEN
        RAISE EXCEPTION 'EPPO data contains an invalid year/month/amount/unit/flow_id';
    END IF;
    IF EXISTS (
        SELECT 1 FROM eppo_values
        GROUP BY reference_year, reference_month, flow_id
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'EPPO data contains duplicate year/month/fuel rows';
    END IF;

    -- Verify the known IDs against the actual database before inserting anything.
    IF NOT EXISTS (SELECT 1 FROM lci_source WHERE source_id = 2) THEN
        RAISE EXCEPTION 'source_id=2 (EPPO) was not found';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM technology WHERE technology_id = 2) THEN
        RAISE EXCEPTION 'technology_id=2 was not found';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM geography WHERE geography_id = 1) THEN
        RAISE EXCEPTION 'geography_id=1 was not found';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM unit WHERE unit_id = 4) THEN
        RAISE EXCEPTION 'unit_id=4 (GWh) was not found';
    END IF;
    IF (SELECT COUNT(*) FROM lci_flow
        WHERE flow_id BETWEEN 6 AND 12
          AND category_id = 1
          AND flow_type = 'PRODUCT') <> 7 THEN
        RAISE EXCEPTION 'Expected flow_id 6-12 to exist as category_id=1, flow_type=PRODUCT';
    END IF;

    -- Do not silently attach to ambiguous pre-existing EPPO processes.
    IF EXISTS (
        SELECT p.process_name
        FROM lci_process p
        WHERE p.source_id = 2
          AND p.process_name IN (
              SELECT 'EPPO Electricity Generation - ' || reference_year::text || '-' || LPAD(reference_month::text, 2, '0')
              FROM (SELECT DISTINCT reference_year, reference_month FROM eppo_values) d
          )
        GROUP BY p.process_name
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Duplicate EPPO process names already exist; resolve them before import';
    END IF;

    -- A matching process must have the expected metadata; otherwise stop safely.
    IF EXISTS (
        SELECT 1
        FROM lci_process p
        JOIN (SELECT DISTINCT reference_year, reference_month FROM eppo_values) d
          ON p.process_name = 'EPPO Electricity Generation - ' || d.reference_year::text || '-' || LPAD(d.reference_month::text, 2, '0')
        WHERE p.source_id = 2
          AND (p.reference_year <> d.reference_year
               OR p.reference_month IS DISTINCT FROM d.reference_month
               OR p.technology_id IS DISTINCT FROM 2
               OR p.geography_id IS DISTINCT FROM 1)
    ) THEN
        RAISE EXCEPTION 'An existing EPPO process has metadata different from the expected values';
    END IF;
END
$validate$;

-- Create only missing monthly EPPO processes.
INSERT INTO lci_process (
    process_name, technology_id, reference_year, geography_id, source_id,
    domain, description, reference_month
)
SELECT DISTINCT
    'EPPO Electricity Generation - ' || reference_year::text || '-' || LPAD(reference_month::text, 2, '0'),
    2,
    reference_year,
    1,
    2,
    'Electricity Generation',
    'Monthly electricity generation by fuel type; source: EPPO; quantity unit: GWh.',
    reference_month
FROM eppo_values v
WHERE NOT EXISTS (
    SELECT 1
    FROM lci_process p
    WHERE p.process_name = 'EPPO Electricity Generation - ' || v.reference_year::text || '-' || LPAD(v.reference_month::text, 2, '0')
      AND p.source_id = 2
);

-- Refuse conflicting existing exchanges. Identical records are retained, not duplicated.
DO $exchange_check$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM eppo_values v
        JOIN lci_process p
          ON p.process_name = 'EPPO Electricity Generation - ' || v.reference_year::text || '-' || LPAD(v.reference_month::text, 2, '0')
         AND p.source_id = 2
        JOIN lci_exchange e
          ON e.process_id = p.process_id
         AND e.flow_id = v.flow_id
         AND e.direction = 'OUTPUT'
         AND e.source_id = 2
        WHERE e.amount IS DISTINCT FROM v.amount
           OR e.unit_id IS DISTINCT FROM 4
           OR e.is_reference_flow IS DISTINCT FROM FALSE
    ) THEN
        RAISE EXCEPTION 'Conflicting EPPO exchange exists (amount/unit/reference-flow mismatch); no changes committed';
    END IF;
END
$exchange_check$;

INSERT INTO lci_exchange (
    process_id, flow_id, direction, amount, unit_id,
    is_reference_flow, source_id, notes
)
SELECT
    p.process_id,
    v.flow_id,
    'OUTPUT',
    v.amount,
    4,
    FALSE,
    2,
    'EPPO monthly electricity generation; unit: GWh.'
FROM eppo_values v
JOIN lci_process p
  ON p.process_name = 'EPPO Electricity Generation - ' || v.reference_year::text || '-' || LPAD(v.reference_month::text, 2, '0')
 AND p.source_id = 2
WHERE NOT EXISTS (
    SELECT 1
    FROM lci_exchange e
    WHERE e.process_id = p.process_id
      AND e.flow_id = v.flow_id
      AND e.direction = 'OUTPUT'
      AND e.source_id = 2
);

-- Import summary before commit.
SELECT
    COUNT(DISTINCT p.process_id) AS eppo_processes,
    COUNT(e.exchange_id) AS eppo_exchanges,
    COUNT(*) FILTER (WHERE e.amount = 0) AS zero_quantity_exchanges,
    MIN(p.reference_year) AS first_year,
    MAX(p.reference_year) AS last_year
FROM lci_process p
JOIN lci_exchange e ON e.process_id = p.process_id
WHERE p.source_id = 2
  AND p.process_name LIKE 'EPPO Electricity Generation - %'
  AND e.source_id = 2;

COMMIT;
